'use client';

import React, { useState } from 'react';
import { useCockpitStore, useVaultStore } from '@/lib/store';
import type { ExportPayload } from '@/lib/types';
import { downloadExport, fetchExportSummary, useApiResource } from '@/lib/api';
import type { ExportKind } from '@/lib/api';
import { DataSourceBadge } from '@/components/vault/ClientVaultDisplay';
import { FileSpreadsheet, Download, ShieldCheck, CheckCircle2, Lock, FileCode } from 'lucide-react';
import Link from 'next/link';

// SAMPLE DATA ONLY: shown (with a "Sample data" label) when the API cannot be reached.
const SAMPLE_SUMMARY: ExportPayload = {
  tallyVouchersAvailable: 1170,
  tallyTotalCreditAmount: 41245000,
  caWorkbookSheetCount: 5,
  integrityScorecard: {
    totalBankLinesIngested: 13359,
    monthsAudited: 18,
    balanceBreaksDetected: 0,
    openingBankBalance: 842100,
    totalBankCredits: 41245000,
    totalBankDebits: 40848100,
    closingBankBalance: 1239000,
    is100PercentTied: true,
    tieVariance: 0,
  },
};

const inr2 = (n: number) => `₹${n.toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
const inr0 = (n: number) => `₹${n.toLocaleString('en-IN', { maximumFractionDigits: 0 })}`;

export default function ExportsPage() {
  const { isUnlocked } = useVaultStore();
  const businessId = useCockpitStore((st) => st.businessId);
  const asOfDate = useCockpitStore((st) => st.asOfDate);
  const role = useCockpitStore((st) => st.role);
  const [downloadSuccess, setDownloadSuccess] = useState<string | null>(null);
  const [downloadError, setDownloadError] = useState<string | null>(null);
  const [busy, setBusy] = useState<ExportKind | null>(null);
  const [ownerPin, setOwnerPin] = useState('');

  const { data, status } = useApiResource((signal) => fetchExportSummary(businessId, asOfDate, signal), [businessId, asOfDate]);
  const summary = data ?? SAMPLE_SUMMARY;
  const sc = summary.integrityScorecard;

  const runDownload = async (kind: ExportKind, okMessage: string, pin?: string) => {
    setBusy(kind);
    setDownloadError(null);
    try {
      const filename = await downloadExport(kind, businessId, asOfDate, { ownerPin: pin });
      setDownloadSuccess(`${okMessage} Saved as ${filename}.`);
      setTimeout(() => setDownloadSuccess(null), 6000);
    } catch (e) {
      setDownloadError(e instanceof Error ? e.message : 'Download failed.');
    } finally {
      setBusy(null);
    }
  };

  const handleDownloadTallyXml = () =>
    runDownload('tally-xml', 'TallyPrime XML voucher pack generated by the API with deterministic GUIDs and CDATA encoding.');

  const handleDownloadCaExcel = () =>
    runDownload('ca-excel', 'CA 5-sheet statutory workbook generated. Route slips and Block D drawer cash are omitted under ADR-004.');

  const handleDownloadInternalPack = () => {
    if (!isUnlocked || role !== 'owner') {
      setDownloadError('Owner PIN authentication is required for the Internal Management Diagnostic Pack.');
      return;
    }
    if (!ownerPin) {
      setDownloadError('Enter the owner PIN to export the internal pack.');
      return;
    }
    const pin = ownerPin;
    setOwnerPin('');
    return runDownload('internal-diagnostic-excel', 'Internal 6-sheet management pack generated.', pin);
  };

  return (
    <div className="flex flex-col gap-6 p-6 max-w-7xl mx-auto">
      {/* Toast Notification */}
      {downloadSuccess && (
        <div className="rounded-xl bg-emerald-50 dark:bg-emerald-950 border border-emerald-300 dark:border-emerald-700 p-4 text-xs font-semibold text-emerald-900 dark:text-emerald-200 flex items-center gap-3 shadow-md">
          <CheckCircle2 className="h-5 w-5 text-emerald-600 flex-shrink-0" />
          <span>{downloadSuccess}</span>
        </div>
      )}

      {downloadError && (
        <div role="alert" className="rounded-xl bg-red-50 dark:bg-red-950 border border-red-300 dark:border-red-800 p-4 text-xs font-semibold text-red-900 dark:text-red-200">
          {downloadError}
        </div>
      )}

      {/* Header */}
      <div>
        <div className="flex items-center gap-2">
          <span className="text-xs font-semibold uppercase tracking-wider text-slate-500">
            Statutory Accounting &amp; Audit Workbooks
          </span>
          <span className="rounded-full bg-emerald-100 dark:bg-emerald-950 text-emerald-700 dark:text-emerald-300 text-[10px] font-bold px-2 py-0.5 border border-emerald-300">
            {status === 'loading' ? 'Checking balance tie…' : sc.is100PercentTied ? '100% Balance Tie Certified' : 'Balance tie mismatch'}
          </span>
          <DataSourceBadge status={status} />
        </div>
        <h2 className="text-2xl font-bold text-slate-900 dark:text-white mt-1">
          Statutory Exports &amp; CA Reconciliation Packs
        </h2>
      </div>

      {/* 1-Click Export Cards */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
        {/* Tally XML Card */}
        <div className="rounded-2xl border border-slate-200 dark:border-slate-800 bg-white dark:bg-slate-900 p-6 shadow-sm flex flex-col justify-between">
          <div>
            <div className="flex items-center gap-3 mb-4">
              <div className="h-10 w-10 rounded-xl bg-amber-100 dark:bg-amber-950/60 flex items-center justify-center text-amber-600">
                <FileCode className="h-5 w-5" />
              </div>
              <div>
                <h3 className="text-base font-bold text-slate-900 dark:text-white">
                  TallyPrime XML Receipt Vouchers
                </h3>
                <span className="text-xs text-slate-500">Format: Pure TDL XML with deterministic GUIDs</span>
              </div>
            </div>

            <p className="text-xs text-slate-600 dark:text-slate-300 mb-4">
              Exports all {summary.tallyVouchersAvailable.toLocaleString('en-IN')} verified AUTO matched bank receipts with immutable Tally GUIDs structured as <code className="font-mono text-emerald-600">&lt;GUID&gt;COPILOT-{businessId}-{'{txn_id}'}&lt;/GUID&gt;</code>. Guaranteed parser compatibility with zero CDATA escaping errors.
            </p>

            <div className="rounded-xl bg-slate-50 dark:bg-slate-800 p-3 text-xs space-y-1 mb-6">
              <div className="flex justify-between">
                <span className="text-slate-500">Auto Receipts Ready:</span>
                <span className="font-bold text-slate-900 dark:text-white font-mono">{summary.tallyVouchersAvailable.toLocaleString('en-IN')} vouchers</span>
              </div>
              <div className="flex justify-between">
                <span className="text-slate-500">Total Credit Volume:</span>
                <span className="font-bold text-slate-900 dark:text-white font-mono">{inr0(summary.tallyTotalCreditAmount)}</span>
              </div>
              <div className="flex justify-between">
                <span className="text-slate-500">MCA Rule 11(g) Edit Log:</span>
                <span className="font-bold text-emerald-600">Compliant</span>
              </div>
            </div>
          </div>

          <button
            onClick={handleDownloadTallyXml}
            disabled={busy !== null}
            className="disabled:opacity-60 w-full flex items-center justify-center gap-2 py-3 bg-slate-900 hover:bg-black text-white dark:bg-slate-100 dark:text-slate-900 dark:hover:bg-white rounded-xl text-xs font-bold shadow-md transition"
          >
            <Download className="h-4 w-4" />
            <span>{busy === 'tally-xml' ? 'Preparing…' : 'Download Tally XML Voucher Pack'}</span>
          </button>
        </div>

        {/* CA 5-Sheet Statutory Excel Card */}
        <div className="rounded-2xl border border-slate-200 dark:border-slate-800 bg-white dark:bg-slate-900 p-6 shadow-sm flex flex-col justify-between">
          <div>
            <div className="flex items-center gap-3 mb-4">
              <div className="h-10 w-10 rounded-xl bg-emerald-100 dark:bg-emerald-950/60 flex items-center justify-center text-emerald-600">
                <FileSpreadsheet className="h-5 w-5" />
              </div>
              <div>
                <h3 className="text-base font-bold text-slate-900 dark:text-white">
                  CA 5-Sheet Statutory Reconciliation Workbook
                </h3>
                <span className="text-xs text-slate-500">Format: OpenPyXL (.xlsx) with Live Tie Formulas</span>
              </div>
            </div>

            <p className="text-xs text-slate-600 dark:text-slate-300 mb-4">
              Tailored specifically for Chartered Accountants and tax auditors. Strictly restricted to formal banking books (Sheets 1–5). Completely omits Sheet 6 route slips and removes Block D drawer cash under ADR-004.
            </p>

            <div className="rounded-xl bg-slate-50 dark:bg-slate-800 p-3 text-xs space-y-1 mb-6">
              <div className="flex justify-between">
                <span className="text-slate-500">Included Sheets:</span>
                <span className="font-bold text-slate-900 dark:text-white">Sheets 1 to 5 (Formal Book)</span>
              </div>
              <div className="flex justify-between">
                <span className="text-slate-500">Sheet 6 Route Slips:</span>
                <span className="font-bold text-emerald-600">Omitted (Split-Plane Firewall)</span>
              </div>
              <div className="flex justify-between">
                <span className="text-slate-500">Formula Tie Verification:</span>
                <span className={`font-bold ${sc.is100PercentTied ? 'text-emerald-600' : 'text-red-600'}`}>
                  {sc.is100PercentTied ? '100% Verified' : 'Mismatch'} ({inr2(Math.abs(sc.tieVariance))} variance)
                </span>
              </div>
            </div>
          </div>

          <button
            onClick={handleDownloadCaExcel}
            disabled={busy !== null}
            className="disabled:opacity-60 w-full flex items-center justify-center gap-2 py-3 bg-emerald-600 hover:bg-emerald-700 text-white rounded-xl text-xs font-bold shadow-md transition"
          >
            <Download className="h-4 w-4" />
            <span>{busy === 'ca-excel' ? 'Preparing…' : 'Download Statutory CA Pack (5-Sheet)'}</span>
          </button>
        </div>
      </div>

      {/* Internal Management Diagnostic Pack (PIN-Gated) */}
      <div className="rounded-2xl border-2 border-dashed border-amber-300 dark:border-amber-700/60 bg-amber-50/30 dark:bg-amber-950/20 p-6">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
          <div>
            <div className="flex items-center gap-2">
              <Lock className="h-4 w-4 text-amber-600" />
              <h3 className="text-base font-bold text-slate-900 dark:text-white">
                Internal Management Diagnostic Pack (6-Sheet Dual-Plane)
              </h3>
            </div>
            <p className="text-xs text-slate-600 dark:text-slate-300 mt-1 max-w-2xl">
              Confidential internal pack for business owners only. Includes Sheet 6 (Salesman Route Slips) and Sheet 1 Block D (Cash Drawer Cross-Check). Strictly prohibited from disclosure to tax auditors.
            </p>
          </div>

          {isUnlocked ? (
            <div className="flex items-center gap-2 flex-shrink-0">
            <input
              type="password"
              inputMode="numeric"
              autoComplete="off"
              aria-label="Owner PIN for the internal pack"
              placeholder="Owner PIN"
              value={ownerPin}
              onChange={(e) => setOwnerPin(e.target.value)}
              onKeyDown={(e) => { if (e.key === 'Enter') handleDownloadInternalPack(); }}
              className="w-28 rounded-xl border border-slate-300 dark:border-slate-600 bg-white dark:bg-slate-900 px-3 py-2 text-xs"
            />
            <button
              onClick={handleDownloadInternalPack}
              disabled={busy !== null}
              className="disabled:opacity-60 flex items-center gap-2 px-5 py-2.5 bg-amber-600 hover:bg-amber-700 text-white text-xs font-bold rounded-xl shadow transition flex-shrink-0"
            >
              <Download className="h-4 w-4" />
              <span>{busy === 'internal-diagnostic-excel' ? 'Preparing…' : 'Export Internal 6-Sheet Pack'}</span>
            </button>
            </div>
          ) : (
            <Link
              href="/lock"
              className="flex items-center gap-2 px-5 py-2.5 bg-amber-600 hover:bg-amber-700 text-white text-xs font-bold rounded-xl shadow transition flex-shrink-0"
            >
              <Lock className="h-4 w-4" />
              <span>Unlock Vault to Export</span>
            </Link>
          )}
        </div>
      </div>

      {/* Data Integrity Matrix Scorecard */}
      <div className="rounded-2xl border border-slate-200 dark:border-slate-800 bg-white dark:bg-slate-900 p-6 shadow-sm">
        <div className="flex items-center justify-between mb-4 pb-3 border-b border-slate-100 dark:border-slate-800">
          <div>
            <h3 className="text-base font-bold text-slate-900 dark:text-white">
              Data Integrity Matrix &amp; Balance Tie Scorecard
            </h3>
            <span className="text-xs text-slate-500">
              Audited across {sc.totalBankLinesIngested.toLocaleString('en-IN')} bank statement rows • {sc.monthsAudited} historical months
            </span>
          </div>

          <div className="flex items-center gap-1.5 px-3 py-1 rounded-full bg-emerald-100 text-emerald-800 dark:bg-emerald-950 dark:text-emerald-300 text-xs font-bold border border-emerald-300">
            <ShieldCheck className="h-4 w-4" />
            <span>{sc.is100PercentTied ? 'Bank Balance 100% Tied' : 'Bank Balance Not Tied'}</span>
          </div>
        </div>

        <div className="grid grid-cols-2 md:grid-cols-4 gap-4">
          <div className="p-3 rounded-xl bg-slate-50 dark:bg-slate-800">
            <span className="text-[11px] font-semibold text-slate-400 block">Opening Bank Balance</span>
            <div className="font-mono text-base font-bold text-slate-900 dark:text-white mt-0.5">
              {inr2(sc.openingBankBalance)}
            </div>
            <span className="text-[10px] text-slate-400">1 April 2025</span>
          </div>

          <div className="p-3 rounded-xl bg-slate-50 dark:bg-slate-800">
            <span className="text-[11px] font-semibold text-emerald-600 dark:text-emerald-400 block">+ Total Bank Credits</span>
            <div className="font-mono text-base font-bold text-emerald-600 dark:text-emerald-400 mt-0.5">
              {inr2(sc.totalBankCredits)}
            </div>
            <span className="text-[10px] text-slate-400">All credit rows</span>
          </div>

          <div className="p-3 rounded-xl bg-slate-50 dark:bg-slate-800">
            <span className="text-[11px] font-semibold text-red-500 block">− Total Bank Debits</span>
            <div className="font-mono text-base font-bold text-red-500 mt-0.5">
              {inr2(sc.totalBankDebits)}
            </div>
            <span className="text-[10px] text-slate-400">All debit rows</span>
          </div>

          <div className="p-3 rounded-xl bg-emerald-50/50 dark:bg-emerald-950/30 border border-emerald-200 dark:border-emerald-800">
            <span className="text-[11px] font-semibold text-emerald-700 dark:text-emerald-300 block">= Closing Bank Balance</span>
            <div className="font-mono text-base font-bold text-emerald-700 dark:text-emerald-300 mt-0.5">
              {inr2(sc.closingBankBalance)}
            </div>
            <span className={`text-[10px] font-bold ${sc.is100PercentTied ? 'text-emerald-600' : 'text-red-600'}`}>Variance: {inr2(sc.tieVariance)}</span>
          </div>
        </div>
      </div>
    </div>
  );
}
